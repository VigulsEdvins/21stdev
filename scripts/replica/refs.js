#!/usr/bin/env node
/**
 * The reference library: every site studied for a replica, by CRM industry.
 *   node scripts/replica/refs.js index            rebuild references/README.md, scripts/preview/catalog.json and the CRM copy
 *   node scripts/replica/refs.js gaps             industries with fewer than 3 native templates (research those before pitching them)
 *   node scripts/replica/refs.js add <host> --slug <slug> --industries id:native,id:borrowed --why "..." [--status built|dropped]
 * references/index.json is the source: one record per site (host, industry map, replica slug, why, status). references/<host>.md is the
 * measured summary copied from reports/replica/<host>/summary.md (reports/ is git-ignored, references/ is kept).
 * "native" = built for that industry; "borrowed" = nearest fit until a native one exists.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', '..');
const REF = path.join(ROOT, 'references');
const CATALOG = path.join(ROOT, 'scripts', 'preview', 'catalog.json');
const CRM_COPY = process.env.CRM_CATALOG || '/home/edvins/system-for-clients/src/data/industryTemplates.json';
const INDUSTRIES = ['buvnieciba', 'autoserviss', 'skaistumkopsana', 'medicina', 'zobarstnieciba', 'turisms', 'tirdznieciba', 'konsultacijas', 'cita']; // the CRM's ClientIndustryId
const load = () => JSON.parse(fs.readFileSync(path.join(REF, 'index.json'), 'utf8'));
const TPL = JSON.parse(fs.readFileSync(path.join(ROOT, 'scripts', 'preview', 'templates.json'), 'utf8'));
const hasLv = slug => fs.existsSync(path.join(ROOT, 'scripts', 'preview', 'lv', slug + '.txt')) || !!(TPL[slug] && TPL[slug].lang === 'lv'); // Latvian text, or a template written in Latvian

function catalog(items) {
  const out = {};
  for (const id of INDUSTRIES) {
    const own = items.filter(i => i.status === 'built' && i.slug && i.industries[id]);
    const order = (a, b) => (hasLv(b.slug) - hasLv(a.slug)) || (a.rank - b.rank);
    const native = own.filter(i => i.industries[id] === 'native').sort(order).map(i => i.slug);
    const borrowed = own.filter(i => i.industries[id] === 'borrowed').sort(order).map(i => i.slug);
    out[id] = { native, borrowed, pick: [...native, ...borrowed].slice(0, 3) };
  }
  return out;
}

function readme(items, cat) {
  const L = ['# Reference library', '', 'Generated by `node scripts/replica/refs.js index`; edit `references/index.json`, not this file.', '', '## Coverage by CRM industry', '', '| Industry | Native | Borrowed | Pitch with |', '|---|---|---|---|'];
  for (const id of INDUSTRIES) L.push(`| ${id} | ${cat[id].native.length} | ${cat[id].borrowed.length} | ${cat[id].pick.join(', ') || '**none, research first**'} |`);
  L.push('', '## Sites', '', '| Site | Replica | Industries | Latvian | Why / status |', '|---|---|---|---|---|');
  for (const i of items) L.push(`| ${i.host} | ${i.slug ? '`' + i.slug + '`' : '-'} | ${Object.entries(i.industries).map(([k, v]) => k + (v === 'native' ? '' : '*')).join(', ') || '-'} | ${i.slug && hasLv(i.slug) ? 'yes' : ''} | ${i.status === 'dropped' ? 'dropped: ' : ''}${i.why} |`);
  L.push('', '`*` = borrowed (nearest fit). Summaries: `references/<host>.md`; thumbnails: `thumbs/<slug>.webp`.', '');
  return L.join('\n');
}

function rebuild() {
  const { items } = load(), cat = catalog(items);
  for (const i of items) if (i.slug && !fs.existsSync(path.join(ROOT, 'features', i.slug))) throw new Error('missing feature folder for ' + i.slug);
  const body = JSON.stringify({ industries: cat }, null, 2) + '\n';
  fs.writeFileSync(CATALOG, body);
  fs.writeFileSync(path.join(REF, 'README.md'), readme(items, cat));
  if (fs.existsSync(path.dirname(CRM_COPY))) fs.writeFileSync(CRM_COPY, body);
  return cat;
}

function copySummaries() {
  for (const i of load().items) {
    const from = path.join(ROOT, 'reports', 'replica', i.host, 'summary.md'), to = path.join(REF, i.host.replace(/\//g, '_') + '.md');
    if (fs.existsSync(from) && !fs.existsSync(to)) fs.copyFileSync(from, to);
  }
}

if (require.main === module) {
  const [cmd, ...a] = process.argv.slice(2), get = k => { const i = a.indexOf('--' + k); return i >= 0 ? a[i + 1] : undefined; };
  try {
    if (cmd === 'index') { copySummaries(); const cat = rebuild(); console.log('ok: ' + INDUSTRIES.map(i => i + ' ' + cat[i].pick.length).join(', ')); }
    else if (cmd === 'gaps') { const cat = catalog(load().items); const g = INDUSTRIES.filter(i => i !== 'cita' && cat[i].native.length < 3); console.log(g.length ? g.map(i => i + ' (native ' + cat[i].native.length + ')').join('\n') : 'no gaps'); }
    else if (cmd === 'add') {
      const j = load(), host = a[0];
      if (!host || j.items.some(i => i.host === host)) throw new Error('host missing or already in the library');
      const ind = Object.fromEntries((get('industries') || '').split(',').filter(Boolean).map(p => { const [k, v] = p.split(':'); if (!INDUSTRIES.includes(k) || !['native', 'borrowed'].includes(v)) throw new Error('bad industry ' + p); return [k, v]; }));
      j.items.push({ host, url: 'https://' + host, slug: get('slug') || null, industries: ind, why: get('why') || '', status: get('status') || 'built', studied: new Date().toISOString().slice(0, 10), rank: j.items.filter(i => i.slug && Object.keys(ind).some(k => i.industries[k])).length + 1 });
      fs.writeFileSync(path.join(REF, 'index.json'), JSON.stringify(j, null, 1) + '\n'); copySummaries(); rebuild(); console.log('added ' + host);
    } else console.log('usage: refs.js index | gaps | add <host> --slug S --industries id:native --why "..."');
  } catch (e) { console.error('error: ' + e.message); process.exit(1); }
}
module.exports = { catalog };
